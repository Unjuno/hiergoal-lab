# Fake executable is generated by serializing fixture strings so quotation and
# newlines cannot corrupt its program source.
def make_fake(path: Path, fix_on_second=True, invalid_plan=False):
    cfg = {
        "plan": PLAN, "fix_parser": FIX_PARSER, "fix_summary": FIX_SUMMARY,
        "fix_on_second": fix_on_second, "invalid_plan": invalid_plan,
    }
    payload = repr(cfg)
    program = r'''#!/usr/bin/env python3
import json, sys
from pathlib import Path
C = CONFIG_MARKER
argv = sys.argv[1:]
prompt = Path(argv[argv.index("--query-file")+1]).read_text(encoding="utf-8")
work = Path(argv[argv.index("--in")+1])
status_file = work / ".fake_count"
n = int(status_file.read_text()) if status_file.exists() else 0
if prompt.startswith("ROLE=PLANNER"):
    response = '{"milestones":[]}' if C["invalid_plan"] else json.dumps(C["plan"])
elif prompt.startswith("ROLE=REPLAN"):
    response = json.dumps({"diagnosis":"Existing code does not satisfy decimal and validation gates",
                           "revised_instruction":"Replace float parsing with Decimal and validate every row"})
elif prompt.startswith("ROLE=EXECUTE"):
    n += 1
    status_file.write_text(str(n))
    if n >= 2 or not C["fix_on_second"]:
        (work / "miniledger" / "parse.py").write_text(C["fix_parser"])
        (work / "miniledger" / "summary.py").write_text(C["fix_summary"])
    response = "Executed repair steps in task workspace."
else:
    response = "UNKNOWN ROLE"
print(json.dumps({"type":"system","subtype":"init","model":"gpt-6-luna",
                  "session_id":"fake-session", "timestamp":1}))
print(json.dumps({"type":"tool_use","name":"terminal","timestamp":2}))
print(json.dumps({"type":"tool_result","name":"terminal","is_error":False, "timestamp":3}))
print(json.dumps({"type":"result","session_id":"fake-session","exit_code":0,
                  "text":response,"tokens":{"input":300,"output":100,"total":400},
                  "duration_ms":30,"timestamp":4}))
'''
    path.write_text(program.replace("CONFIG_MARKER", payload), encoding="utf-8")
    path.chmod(0o755)


class PlanContractTests(unittest.TestCase):
    def test_valid_plan_produces_three_levels_and_exact_coverage(self):
        state = validate_plan(PLAN)
        self.assertEqual(state["root"]["goal"], ROOT_GOAL)
        self.assertEqual(len(state["milestones"]), 3)
        self.assertEqual(len(state["leaves"]), 3)
        self.assertEqual(set(c for x in state["leaves"].values() for c in x["checks"]), set(GATES))

    def test_missing_criterion_rejected(self):
        doc = json.loads(json.dumps(PLAN))
        doc["milestones"][-1]["subgoals"][0]["checks"] = ["invalid_rows"]
        with self.assertRaises(PlanError):
            validate_plan(doc)

    def test_dependency_cycle_rejected(self):
        doc = json.loads(json.dumps(PLAN))
        doc["milestones"][0]["subgoals"][0]["depends_on"] = ["S3"]
        with self.assertRaisesRegex(PlanError, "Circular"):
            validate_plan(doc)

    def test_replan_keeps_root_and_rewires_dependent_leaf(self):
        state = validate_plan(PLAN)
        state["leaves"]["S1"]["status"] = "failed"
        new = replace_failed_leaf(state, "S1", "Use exact Decimal in input handling",
                                  "Input parser accepts unsupported values")
        self.assertEqual(new["id"], "S1r1")
        self.assertEqual(new["parent"], "M1")
        self.assertEqual(new["checks"], ["invalid_rows", "blank_rows"])
        self.assertEqual(state["leaves"]["S2"]["depends_on"], ["S1r1"])
        self.assertEqual(state["leaves"]["S1"]["status"], "superseded")
        self.assertEqual(state["root"]["goal"], ROOT_GOAL)

    def test_json_fence_supported(self):
        parsed = parse_object(chr(96)*3 + "json\n" + json.dumps(PLAN) + "\n" + chr(96)*3)
        self.assertEqual(parsed, PLAN)


class ControllerOfflineIntegration(unittest.TestCase):
    def invoke(self, fix_on_second=True, invalid_plan=False, add_ack=True):
        with tempfile.TemporaryDirectory() as folder:
            temp = Path(folder)
            binary = temp / "fake-hermes"
            make_fake(binary, fix_on_second, invalid_plan)
            args = [sys.executable, "-m", "hiergoal.controller", "--hermes", str(binary),
                    "--output", str(temp / "runs"), "--max-calls", "10",
                    "--max-replans", "1", "--timeout-seconds", "30"]
            if add_ack:
                args.append("--ack-unsandboxed")
            run = subprocess.run(args, cwd=ROOT, text=True, capture_output=True, timeout=80)
            dirs = list((temp / "runs").glob("hiergoal-*")) if (temp / "runs").exists() else []
            records, state = None, None
            if dirs:
                data = dirs[0]
                if (data / "records.json").exists():
                    records = json.loads((data / "records.json").read_text())
                if (data / "state.json").exists():
                    state = json.loads((data / "state.json").read_text())
            return run, records, state

    def test_replan_and_verified_completion(self):
        run, records, state = self.invoke()
        self.assertEqual(run.returncode, 0, run.stderr + "\n" + run.stdout)
        self.assertEqual(records["outcome"], "PASS")
        self.assertEqual(state["root"]["status"], "completed")
        self.assertEqual(state["replans"], 1)
        self.assertEqual(state["leaves"]["S1"]["status"], "superseded")
        self.assertEqual(state["leaves"]["S1r1"]["status"], "completed")
        self.assertEqual(records["final_independent"]["tests_run"], 6)
        self.assertTrue(records["original_visible_tests_unchanged"])
        self.assertGreaterEqual(len(records["calls"]), 4)

    def test_model_plan_missing_gates_is_rejected(self):
        run, records, state = self.invoke(invalid_plan=True)
        self.assertNotEqual(run.returncode, 0)
        self.assertEqual(records["outcome"], "FAIL")
        self.assertIn("Invalid model plan", records["halt_reason"])

    def test_unsandboxed_run_is_explicitly_blocked(self):
        run, records, state = self.invoke(add_ack=False)
        self.assertEqual(run.returncode, 2)
        self.assertIn("--ack-unsandboxed", run.stderr)
        self.assertIsNone(records)

    def test_dry_run_does_not_invoke_model(self):
        run = subprocess.run(
            [sys.executable, "-m", "hiergoal.controller", "--dry-run"],
            cwd=ROOT, text=True, capture_output=True, timeout=30)
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertIn("No Hermes / OpenAI calls made", run.stdout)


